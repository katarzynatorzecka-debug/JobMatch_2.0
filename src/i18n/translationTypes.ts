export type TranslationKey = keyof TranslationParameters

export type TranslationDictionary = {
  [Key in TranslationKey]: string
}

export type Translate = <Key extends TranslationKey>(
  key: Key,
  ...parameters: TranslationParameters[Key] extends undefined
    ? []
    : [parameters: TranslationParameters[Key]]
) => string

export function translationParameterNames(template: string): string[] {
  return [...template.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)]
    .map((match) => match[1])
    .filter((name, index, names) => names.indexOf(name) === index)
    .sort()
}

export function interpolateTranslation(
  template: string,
  parameters?: Record<string, TranslationPrimitive>,
): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) => (
    parameters && Object.prototype.hasOwnProperty.call(parameters, name)
      ? String(parameters[name])
      : placeholder
  ))
}
